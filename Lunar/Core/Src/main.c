static void Pump_TestTask(void)
{
    static uint8_t pump_state = 0U;

    /*
     * 第一次调用立即执行；
     * 此后每隔 2000 ms 执行一次。
     */
    PERIODIC(10000U);

    if (pump_state == 0U)
    {
        /* 水泵以 30% 占空比启动 */
        MOTOR_Forward(800U);
        pump_state = 1U;
    }
    else if (pump_state == 1U)
    {
        /* 运行两秒后停止，只执行一次 */
        MOTOR_Stop();
        pump_state = 2U;
    }
}


static void Temperature_Task(void)
{
    int32_t temperature_x100;
    uint32_t abs_temperature;

    /* The DS18B20 conversion is asynchronous; this task only runs every 750 ms. */
    PERIODIC(750U);

    temperature_b6_status = DS18B20_ReadTemperature(
        B6_GPIO_Port, B6_Pin, &temperature_b6);
    temperature_b7_status = DS18B20_ReadTemperature(
        B7_GPIO_Port, B7_Pin, &temperature_b7);

    if (temperature_b6_status != DS18B20_OK)
    {
        if (temperature_b6_status != DS18B20_BUSY)
        {
            OLED_ShowString(2, 1, "Read ERROR      ");
        }
        return;
    }

    if (temperature_b6 >= 0.0f)
    {
        temperature_x100 = (int32_t)(temperature_b6 * 100.0f + 0.5f);
    }
    else
    {
        temperature_x100 = (int32_t)(temperature_b6 * 100.0f - 0.5f);
    }

    if (temperature_x100 < 0)
    {
        abs_temperature = (uint32_t)(-temperature_x100);
    }
    else
    {
        abs_temperature = (uint32_t)temperature_x100;
    }

    OLED_ShowString(2, 1, "                ");
    OLED_ShowString(2, 1, "Temp:");
    OLED_ShowChar(2, 6, temperature_x100 < 0 ? '-' : ' ');
    OLED_ShowNum(2, 7, abs_temperature / 100U, 3);
    OLED_ShowChar(2, 10, '.');
    OLED_ShowNum(2, 11, abs_temperature % 100U, 2);
    OLED_ShowString(2, 13, " C");
}

